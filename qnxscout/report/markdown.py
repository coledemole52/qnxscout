"""Markdown report: paste into an issue, a PR comment or a port's REPORT.md."""
from __future__ import annotations

import os
from collections import defaultdict

from .. import kb

ICON = {"blocker": "⛔", "runtime": "💥", "link": "🔗", "review": "🔍", "info": "ℹ️"}


def render(result, max_per_rule: int = 8) -> str:
    sc = result.score
    name = os.path.basename(result.root.rstrip("/"))
    lines = [f"# QNX 8.0 port-readiness: `{name}`", "",
             f"**Grade {sc['grade']} - {sc['label']}** · effort points {sc['points']} · "
             f"{sc['distinct_rules']} distinct issues · ~{sc['files_to_touch']} files to touch", "",
             "| Severity | Findings |", "|---|---|"]
    for s, n in sc["by_severity"].items():
        lines.append(f"| {ICON[s]} {s} | {n} |")
    lines.append("")
    if sc["link_flags"]:
        lines += [f"**QNX link additions:** `{' '.join(sc['link_flags'])}`", ""]
    lines.append(f"Scanned {result.c_files} C/C++ files and {result.build_files} build files "
                 f"({', '.join(result.build_systems) or 'no build system detected'}).")
    lines.append("")
    groups = defaultdict(list)
    for f in result.findings:
        if f.severity != "info":
            groups[(f.severity, f.rule)].append(f)
    order = {s: i for i, s in enumerate(kb.SEVERITIES)}
    for (sev, rid), fs in sorted(groups.items(), key=lambda kv: (order[kv[0][0]], kv[0][1])):
        r = kb.RULES_BY_ID[rid]
        lines += [f"## {ICON[sev]} {rid} {r.title}", "", r.why, "", f"**Fix:** {r.fix}", ""]
        for f in fs[:max_per_rule]:
            cond = "" if f.confidence == "high" else " _(conditional)_"
            lines.append(f"- `{f.file}:{f.line}` {f.message}{cond}")
        if len(fs) > max_per_rule:
            lines.append(f"- … and {len(fs) - max_per_rule} more")
        lines.append("")
        lines.append("Evidence: " + " · ".join(f"[{label}]({url})" for label, url in r.evidence_links()))
        lines.append("")
    if not groups:
        lines.append("No QNX porting issues found.")
    lines.append("")
    lines.append("_Generated by qnxscout. Static analysis predicts porting work; confirm by building on QNX._")
    return "\n".join(lines)
